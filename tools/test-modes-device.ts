import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { requestHttp, colorSchema } from '../shared/protocol/src/index.js';
const address = process.env.DEVICE_ADDRESS;
if (!address) throw new Error('Set DEVICE_ADDRESS');
let id = 1, scriptId: string | undefined;
const current = (await requestHttp(address, { id: id++, operation: 0 })).state!;
const initial = process.env.RESTORE_STATE_FILE ? JSON.parse(readFileSync(process.env.RESTORE_STATE_FILE, 'utf8')) : current;
assert.equal(current.build, Number(process.env.TARGET_BUILD ?? 11));
assert.equal(current.deviceId, initial.deviceId);
assert.deepEqual(current.config, initial.config);
try {
  await requestHttp(address, { id: id++, operation: 2, brightness: 16 });
  let result = await requestHttp(address, { id: id++, operation: 1, color: colorSchema.parse({ red: 255 }) });
  assert.equal(result.state!.mode, 0);
  const source = 'function setup() for i=0,luxio_get_pixel_count()-1 do luxio_set_pixel_color(i,0,100,255) end end function loop() error("Gradient loop must never execute") end';
  const created = await requestHttp(address, { id: id++, operation: 7, script: { id: '', name: 'Temporary firmware mode test', source, mode: 1 } });
  scriptId = created.script!.id;
  assert.equal(created.script!.mode, 1);
  result = await requestHttp(address, { id: id++, operation: 10, scriptId });
  assert.equal(result.state!.mode, 1);
  await new Promise(resolve => setTimeout(resolve, 1100));
  result = await requestHttp(address, { id: id++, operation: 0 });
  assert.equal(result.state!.mode, 1); assert.equal(result.state!.activeScriptId, scriptId);
  result = await requestHttp(address, { id: id++, operation: 15, on: false });
  assert.equal(result.state!.mode, 1);
  console.log('PASS: Color → Gradient; setup-only execution; power off preserves Gradient');
  await requestHttp(address, { id: id++, operation: 8, script: { id: scriptId, name: 'Temporary firmware mode test', source: 'function setup() end function loop() for i=0,luxio_get_pixel_count()-1 do luxio_set_pixel_color(i,0,255,0) end end', mode: 2 } });
  result = await requestHttp(address, { id: id++, operation: 10, scriptId });
  assert.equal(result.state!.mode, 2);
  result = await requestHttp(address, { id: id++, operation: 2, brightness: 16 });
  assert.equal(result.state!.mode, 2);
  await new Promise(resolve => setTimeout(resolve, 800));
  result = await requestHttp(address, { id: id++, operation: 0 });
  assert.equal(result.state!.mode, 2);
  result = await requestHttp(address, { id: id++, operation: 11 });
  assert.equal(result.state!.mode, 0);
  console.log('PASS: Gradient → Animation; brightness preserves Animation; stop returns Color');
  await requestHttp(address, { id: id++, operation: 8, script: { id: scriptId, name: 'Temporary firmware mode test', source, mode: 2 } });
  await requestHttp(address, { id: id++, operation: 10, scriptId });
  await new Promise(resolve => setTimeout(resolve, 200));
  result = await requestHttp(address, { id: id++, operation: 0 });
  assert.equal(result.state!.mode, 0); assert.equal(result.state!.activeScriptId, '');
  console.log('PASS: Animation loop errors reset mode and restore solid color');
} finally {
  if (scriptId) await requestHttp(address, { id: id++, operation: 9, scriptId });
  await requestHttp(address, { id: id++, operation: 1, color: initial.color });
  await requestHttp(address, { id: id++, operation: 2, brightness: initial.brightness });
  if (initial.activeScriptId) await requestHttp(address, { id: id++, operation: 10, scriptId: initial.activeScriptId });
  await requestHttp(address, { id: id++, operation: 15, on: initial.on });
  console.log('Original strip state restored.');
}
